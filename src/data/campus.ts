import type { CampusMap, InteriorDef, PropDef, PropKind, Rect } from '../types';

const r = (x: number, y: number, w: number, h: number): Rect => ({ x, y, w, h });
const prop = (kind: PropKind, x: number, y: number, label?: string, scale?: number): PropDef => ({
  kind,
  x,
  y,
  label,
  scale,
});
const row = (kind: PropKind, x0: number, x1: number, step: number, y: number): PropDef[] => {
  const out: PropDef[] = [];
  for (let x = x0; x <= x1; x += step) out.push(prop(kind, x, y));
  return out;
};

